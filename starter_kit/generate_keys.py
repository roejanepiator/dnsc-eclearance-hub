"""Generate secret keys for the DNSC e-Clearance Hub and write them to .env

Usage:  python3 generate_keys.py            # creates .env (refuses to overwrite)
        python3 generate_keys.py --force    # regenerate and overwrite .env

Keys are produced with the `secrets` module (cryptographically secure).
.env is created with owner-only permissions (chmod 600). NEVER commit it to git.
"""
import os
import secrets
import stat
import sys

ENV_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env")

KEYS = {
    # Used by registrar_mock_api.py (server) and your Hub's Registrar client (X-API-Key header)
    "REGISTRAR_API_KEY": lambda: "reg_" + secrets.token_urlsafe(32),
    # YOUR system's HMAC key for signing/verifying manifests it produces (R14)
    "HMAC_SIGNING_KEY": lambda: secrets.token_hex(32),
    # Session/JWT/CSRF signing for your web app
    "APP_SECRET_KEY": lambda: secrets.token_urlsafe(48),
}

# Fixed value from the starter kit README. It is ONLY for verifying the provided
# sample files (they were signed with it). Not secret, not for your own system.
STATIC = {
    "STARTER_HMAC_KEY": "it312-starter-demo-key-change-me",
    "REGISTRAR_BASE_URL": "http://127.0.0.1:8001/api/v1",
}


def main():
    if os.path.exists(ENV_PATH) and "--force" not in sys.argv:
        sys.exit(f"{ENV_PATH} already exists. Use --force to regenerate (old keys will be lost).")
    lines = ["# Generated by generate_keys.py - DO NOT COMMIT", ""]
    lines += [f"{name}={make()}" for name, make in KEYS.items()]
    lines += [""] + [f"{k}={v}" for k, v in STATIC.items()]
    with open(ENV_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    os.chmod(ENV_PATH, stat.S_IRUSR | stat.S_IWUSR)  # 600
    print(f"Wrote {ENV_PATH} with {len(KEYS)} generated keys.")


if __name__ == "__main__":
    main()
